"""Converts the row icons of the approved AirPods Settings design (Appendix B of the design spec:
the <symbol id="i-*"> definitions in docs/design/airpods-settings-ui-2026-09-29.html) to Android
VectorDrawable XML, one file per icon: stroke only, 24 x 24, stroke 1.8, round caps and joins,
colour black (Settings tints the bitmap with its own row-icon colour). Handles <path>, <circle>
and <rect>; anything else is an error. Usage: svg-icons-to-vector-drawables.py <output-dir>"""
import os, re, sys
from xml.etree import ElementTree as ET

ICONS = ["ear", "voice", "tune", "eq", "squeeze", "pin", "sound", "edit", "music", "phone", "reset", "wave"]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "docs", "design", "airpods-settings-ui-2026-09-29.html")

def num(x):
    return ("%.4f" % float(x)).rstrip("0").rstrip(".")

def circle(el):
    cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
    return "M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0" % (num(cx - r), num(cy), num(r), num(r), num(2 * r), num(r), num(r), num(-2 * r))

def rect(el):
    x, y, w, h = (float(el.get(k)) for k in ("x", "y", "width", "height"))
    rx = float(el.get("rx", "0"))
    return ("M%s,%s H%s A%s,%s 0 0 1 %s,%s V%s A%s,%s 0 0 1 %s,%s H%s A%s,%s 0 0 1 %s,%s V%s A%s,%s 0 0 1 %s,%s z" % (
        num(x + rx), num(y), num(x + w - rx), num(rx), num(rx), num(x + w), num(y + rx),
        num(y + h - rx), num(rx), num(rx), num(x + w - rx), num(y + h),
        num(x + rx), num(rx), num(rx), num(x), num(y + h - rx),
        num(y + rx), num(rx), num(rx), num(x + rx), num(y)))

def convert(name, symbol):
    paths = []
    for el in symbol:
        tag = el.tag.split("}")[-1]
        if tag == "path": paths.append(el.get("d"))
        elif tag == "circle": paths.append(circle(el))
        elif tag == "rect": paths.append(rect(el))
        else: raise SystemExit("unsupported element <%s> in i-%s" % (tag, name))
    body = "\n".join(
        '    <path\n        android:pathData="%s"\n        android:strokeColor="#FF000000"\n'
        '        android:strokeWidth="1.8"\n        android:strokeLineCap="round"\n'
        '        android:strokeLineJoin="round" />' % d for d in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/design/svg-icons-to-vector-drawables.py from the approved design '
            '(icon i-%s). Do not edit by hand. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n%s\n</vector>\n') % (name, body)

def main(out):
    html = open(SRC).read()
    os.makedirs(out, exist_ok=True)
    for name in ICONS:
        m = re.search(r'<symbol id="i-%s"[^>]*>(.*?)</symbol>' % name, html, re.S)
        if not m: raise SystemExit("icon i-%s not found" % name)
        symbol = ET.fromstring("<s>%s</s>" % m.group(1))
        open(os.path.join(out, "ic_airpods_%s.xml" % name), "w").write(convert(name, symbol))
        print("wrote ic_airpods_%s.xml" % name)

if __name__ == "__main__":
    if len(sys.argv) != 2: raise SystemExit(__doc__)
    main(sys.argv[1])
